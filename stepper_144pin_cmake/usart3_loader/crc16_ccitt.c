/*******************************************************************************
 * Public Function Definitions
 *******************************************************************************/
uint16_t crc16_ccitt_update(uint16_t running_crc, const uint8_t *data, size_t length) {
  uint16_t crc = running_crc;
  size_t byte_index;
  uint8_t bit_index;

  if (data != NULL) {
    for (byte_index = 0u; byte_index < length; byte_index++) {
      crc = (uint16_t)(crc ^ ((uint16_t)data[byte_index] << 8));

      for (bit_index = 0u; bit_index < 8u; bit_index++) {
        if ((crc & 0x8000u) != 0u) {
          crc = (uint16_t)((crc << 1) ^ CRC16_CCITT_POLYNOMIAL);
        } else {
          crc = (uint16_t)(crc << 1);
        }
      }
    }
  }

  return crc;
}

